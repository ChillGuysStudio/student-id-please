#!/usr/bin/env python3
"""Generate compose.replicas.yaml with replicas 2..N of each domain service.

compose.yaml defines replica 1 of every domain service. Set REPLICAS in .env for all
services, or <SERVICE>_REPLICAS (for example SESSION_REPLICAS=3) for one service, then
run this script and `docker compose up -d`. Lowering a count removes those replicas on
the next `docker compose up -d --remove-orphans`.

Each extra replica keeps a stable instance ID derived from REPLICA_SEED in .env, its own
address and network alias (<service>-slot-<n>), and, for Discord DMs, its own host port
for the direct WebSocket. The file is ignored by Git and never contains secrets.
"""
import argparse
from pathlib import Path
import uuid

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = "compose.replicas.yaml"
# service name in compose.yaml -> (.env prefix, container port)
SERVICES = {
    "applicant": ("APPLICANT", 8081),
    "credential": ("CREDENTIAL", 8082),
    "university-record": ("UNIVERSITY_RECORD", 8006),
    "server-rules": ("SERVER_RULES", 8005),
    "moderation": ("MODERATION", 8000),
    "player": ("PLAYER", 8001),
    "session": ("SESSION", 8002),
    "discord-dms": ("DISCORD_DMS", 8000),
}


def read_env(path):
    values = {}
    for line in path.read_text().splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip().strip("'\"")
    return values


def replica_count(env, prefix):
    raw = env.get(f"{prefix}_REPLICAS") or env.get("REPLICAS") or "2"
    count = int(raw)
    if not 1 <= count <= 9:
        raise ValueError(f"{prefix}_REPLICAS must be between 1 and 9, got {raw}")
    return count


def instance_id(seed, service, slot):
    return uuid.uuid5(uuid.UUID(seed), f"{service}/{slot}")


def render(env):
    seed = env.get("REPLICA_SEED")
    if not seed:
        raise ValueError("REPLICA_SEED is missing from .env; run scripts/setup.py")
    dms_base = int(env.get("DMS_REPLICA_PORT_BASE") or 18009)
    lines = ["# Generated by scripts/replicas.py from REPLICAS in .env. Do not edit.", "services:"]
    for service, (prefix, port) in SERVICES.items():
        for slot in range(2, replica_count(env, prefix) + 1):
            name = f"{service}-slot-{slot}"
            lines += [
                f"  {name}:",
                f"    extends:",
                f"      file: compose.yaml",
                f"      service: {service}",
                f"    environment:",
                f"      INSTANCE_ID: {instance_id(seed, service, slot)}",
                f"      INSTANCE_HTTP_URL: http://{name}:{port}",
            ]
            if service == "discord-dms":
                host_port = dms_base + slot - 2
                lines += [f"      INSTANCE_WS_URL: ws://localhost:{host_port}",
                          f"    ports: !override",
                          f"      - '127.0.0.1:{host_port}:8000'"]
            lines += [f"    networks: !override", f"      default:", f"        aliases: [{name}]"]
    if lines[-1] == "services:":
        lines[-1] = "services: {}"
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--env", default=str(ROOT / ".env"))
    args = parser.parse_args()
    env = read_env(Path(args.env))
    (ROOT / OUTPUT).write_text(render(env))
    counts = ", ".join(f"{s}={replica_count(env, p)}" for s, (p, _) in SERVICES.items())
    print(f"Wrote {OUTPUT}: {counts}")


if __name__ == "__main__":
    main()
